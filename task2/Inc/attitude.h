#ifndef __ATTITUDE_H
#define __ATTITUDE_H

#include <stdint.h>

/* ============================================================================
 * 互补滤波姿态解算（Plan B：芯片 DMP 引擎无效时的替代方案）
 * ----------------------------------------------------------------------------
 * 原理：陀螺积分（快、平滑、但漂移） 与 加速度计重力向量（慢、有噪声、
 * 但长期不漂） 按固定比例融合：
 *     角度 = 98% × 陀螺积分 + 2% × 加速度角
 * 等效一阶低通时间常数 ≈ 0.02 / 0.005 = 0.25s（5ms 周期下）。
 *
 * 局限（如实告知）：
 *   - yaw 没有磁力计参考，只能陀螺积分，会缓慢漂移；
 *   - 高动态（甩动）时加速度计不可信，代码里已做模长门限保护；
 *   - 与 DMP 的卡尔曼/融合算法相比精度低，但曲线趋势正确。
 * ============================================================================*/

void  Attitude_Reset(void);
/* 每个周期调用一次（dt 传固定 0.005f，5ms 绝对周期） */
void  Attitude_Update(const int16_t accel[3], const int16_t gyro[3], float dt);
float Attitude_GetPitch(void);   /* °  */
float Attitude_GetRoll(void);    /* °  */
float Attitude_GetYaw(void);     /* °（积分值，会缓慢漂移） */

#endif /* __ATTITUDE_H */
